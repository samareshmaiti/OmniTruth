CREATE TABLE IF NOT EXISTS public.platform_admin_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   issuer VARCHAR(512) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    tenant_id UUID NOT NULL,
    app_role VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_platform_admin_identity
    UNIQUE (issuer, subject, tenant_id, app_role)
    );

CREATE INDEX IF NOT EXISTS idx_platform_admin_identity_lookup
    ON public.platform_admin_identities
    (issuer, subject, tenant_id, active);